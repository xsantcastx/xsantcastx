/**
 * item-icon-shapes.ts — the silhouettes of the pixel item icons (item-icons.ts).
 *
 * One 16 × 16 grid per kind of thing (a sword, a helm, an ore, a potion…), drawn
 * once and tinted per item by its material. Rows may be shorter than 16 (the
 * renderer pads them) and the drawing need not be centred: the renderer centres
 * the filled box and adds the outline itself, so a shape is only ever the body.
 *
 * Tones, light from the upper left (docs/art/style-guide.md §4):
 *   primary material   D deep · d shade · b base · l lit · h highlight
 *   second material    w shade · v base · u lit        (hafts, cords, pages, corks)
 *   accent             e shade · a base · A lit · G glow (gems, trims, liquids, veins)
 *   s                  a one-pixel white shine
 *   .                  clear
 *
 * Pure data. No DOM.
 */
