#!/usr/bin/env node
/**
 * generate-market-reference.mjs — copy the Exchange catalogue's base worth and
 * the inventory constants the market server needs into
 * `functions/src/market/reference.generated.ts`.
 *
 * The Cloud Functions package cannot import Angular-side TypeScript (it is
 * compiled and deployed on its own), so the server carries a generated copy.
 * `src/app/shared/market/market-reference.spec.ts` fails if the copy drifts
 * from the live catalogue, so a price or catalogue change that forgets to
 * re-run this is caught by the unit suite rather than by a rejected order.
 *
 *   node scripts/generate-market-reference.mjs
 */
import { createRequire } from 'node:module';
import { writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(root, 'package.json'));
// esbuild is not a direct dependency; @angular/build ships it.
const esbuild = require(require.resolve('esbuild', { paths: [dirname(require.resolve('@angular/build/package.json'))] }));

const entry = `
import { EXCHANGE_CATALOGUE } from './src/app/shared/exchange/exchange.model';
import { INVENTORY_ERA, INVENTORY_BAG_CAP } from './src/app/shared/rpg/inventory.model';
export const out = {
  era: INVENTORY_ERA,
  bagCap: INVENTORY_BAG_CAP,
  goods: EXCHANGE_CATALOGUE.map(g => ({
    id: g.id, kind: g.kind, rarity: g.rarity, basePrice: g.basePrice,
    stackKey: g.stackKey ?? null, definitionId: g.definitionId ?? null, name: g.name,
  })),
};
`;

const dir = mkdtempSync(join(tmpdir(), 'market-ref-'));
const outfile = join(dir, 'ref.mjs');
try {
  await esbuild.build({
    stdin: { contents: entry, resolveDir: root, loader: 'ts' },
    bundle: true,
    platform: 'node',
    format: 'esm',
    outfile,
    logLevel: 'error',
    loader: { '.png': 'empty', '.webp': 'empty', '.jpg': 'empty', '.svg': 'empty', '.css': 'empty' },
  });
  const { out } = await import(pathToFileURL(outfile).href);
  const lines = out.goods
    .slice()
    .sort((a, b) => a.id.localeCompare(b.id))
    .map(g => `  ${JSON.stringify(g.id)}: ${JSON.stringify({
      kind: g.kind, rarity: g.rarity, basePrice: g.basePrice,
      ...(g.stackKey ? { stackKey: g.stackKey } : {}),
      ...(g.definitionId ? { definitionId: g.definitionId } : {}),
      name: g.name,
    })},`);
  const file = `/* eslint-disable */
// GENERATED by scripts/generate-market-reference.mjs — do not edit by hand.
// Pinned against the live catalogue by src/app/shared/market/market-reference.spec.ts.

export interface ReferenceGood {
  kind: "material" | "equipment";
  rarity: string;
  basePrice: number;
  stackKey?: string;
  definitionId?: string;
  name: string;
}

/** INVENTORY_ERA from src/app/shared/rpg/inventory.model.ts. */
export const INVENTORY_ERA = ${out.era};
/** INVENTORY_BAG_CAP from src/app/shared/rpg/inventory.model.ts. */
export const INVENTORY_BAG_CAP = ${out.bagCap};

export const REFERENCE_GOODS: Readonly<Record<string, ReferenceGood>> = {
${lines.join('\n')}
};
`;
  const target = join(root, 'functions', 'src', 'market', 'reference.generated.ts');
  writeFileSync(target, file);
  console.log(`market reference: ${out.goods.length} goods, era ${out.era} -> ${target}`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
