#!/usr/bin/env python3
"""
build-scene-art.py — turns a painted location into the four files a scene needs.

Every full-bleed background on the site ships as three WebP widths plus one
JPEG, and `<picture>` picks between them before it fetches anything. The widths
are not just scales of each other:

  768   a PORTRAIT crop, 3:4. A phone showing the landscape frame squeezed into
        a tall viewport shows mostly floor and ceiling, so the phone gets the
        middle of the painting at full height instead. This is art direction,
        and it is why the mobile source cannot be generated by `resize` alone.
  1280  the landscape frame, scaled.
  1536  the landscape frame at source resolution.
  .jpg  the same 1536 frame, for browsers with no WebP. Last resort, and the
        only file here a modern browser never downloads.

It also converts the 33 painted rune/runeword/artifact cards.

  A NOTE ON THE CARDS, because the brief asked for PNG "for transparency":
  none of the 33 has any. Measured — every one is RGBA with an alpha channel
  whose extrema are (255, 255), i.e. fully opaque. They are rectangular cards
  with painted borders, not cut-out glyphs, so the alpha channel is 33 files'
  worth of a constant. Dropping it and encoding WebP takes the set from 2.7 MB
  to ~0.35 MB with no visible change: at 3x zoom on the card titles — the
  finest detail on any of them — q88 and the source PNG are indistinguishable.

  These are WebP-only, with no PNG beside them, which is the one place this
  file departs from the <picture> pattern above. The heroes carry a JPEG
  because they are the largest contentful paint on public pages. The cards are
  behind a route that needs JavaScript and localStorage to show anything, so a
  browser too old for WebP (pre-Safari-14, 2020) never reaches them.

Run from the repo root:  python3 scripts/build-scene-art.py [--only=<stem>]... [--check]
`--only=bg-town-infernal` builds one scene and skips the cards — use it when a
single painting lands, so a full run does not re-encode every committed scene.
`--check` lists which scenes have a source painting and writes nothing.
Idempotent — safe to re-run; it overwrites its own outputs and nothing else.
"""
import os
import sys

from PIL import Image

# The library moved off the Desktop (`~/Desktop/Game images/` no longer exists);
# same root and override as import-assets.py.
LIBRARY = os.path.expanduser(
    os.environ.get('ER_ASSET_LIBRARY', '~/Documents/1. Projects/Eclipse Realms/Assets')
)
SRC_DIR = os.path.join(LIBRARY, 'Locations')
OUT_DIR = os.path.join(os.path.dirname(__file__), '..', 'src', 'assets', 'images')

# source basename -> output basename. RuneForge is deliberately absent: it
# already shipped as runeforge-hero-* in v2.52.0 and regenerating it here would
# churn four committed binaries for a byte-level difference nobody can see.
# Paths are relative to `Locations/`, without `.png`, and use the library's own
# kebab-case names (the Desktop folder had `The Arena.png`).
SCENES = {
    'the-arena': 'bg-arena',
    'market': 'bg-market',
    'war-table': 'bg-war-table',
    'profile': 'bg-profile',
    'umbral': 'bg-umbral',
    'luminous': 'bg-luminous',
    'celestial': 'bg-celestial',
    'verdant': 'bg-verdant',
    'infernal': 'bg-infernal',
    'basalt-seamworks': 'bg-basalt-seamworks',
}

# Realm towns for the in-world hubs, commissioned in docs/art-commissions/.
# None is painted yet; a missing source is skipped, not an error, so the day one
# lands `--only=bg-town-<realm>` is the whole job.
TOWNS = {
    'Towns/luminous-town': 'bg-town-luminous',
    'Towns/celestial-town': 'bg-town-celestial',
    'Towns/infernal-town': 'bg-town-infernal',
    'Towns/umbral-town': 'bg-town-umbral',
    'Towns/verdant-town': 'bg-town-verdant',
}

# Matched to the art already on the wall rather than picked: re-encoding
# RuneForge.png at these two values reproduces the committed
# runeforge-hero-1536.webp (174 KB) and .jpg (246 KB) to within a few KB. A
# scene that is visibly crisper than the forge is a scene that looks like it
# came from a different site.
WEBP_QUALITY = 78
JPEG_QUALITY = 79


def build(src_path: str, stem: str) -> list[tuple[str, int]]:
    img = Image.open(src_path).convert('RGB')
    w, h = img.size
    written = []

    # 768 — portrait crop, taken from the horizontal centre. The paintings are
    # all composed on a central subject (an anvil, a throne, a war table), so
    # the centre is the one crop that never loses it.
    left = (w - int(h * 3 / 4)) // 2
    portrait = img.crop((left, 0, left + int(h * 3 / 4), h)).resize((768, 1024), Image.LANCZOS)
    p = os.path.join(OUT_DIR, f'{stem}-768.webp')
    portrait.save(p, 'WEBP', quality=WEBP_QUALITY, method=6)
    written.append((p, os.path.getsize(p)))

    # 1280 and 1536 — the landscape frame.
    for width in (1280, 1536):
        scaled = img if width == w else img.resize((width, round(h * width / w)), Image.LANCZOS)
        p = os.path.join(OUT_DIR, f'{stem}-{width}.webp')
        scaled.save(p, 'WEBP', quality=WEBP_QUALITY, method=6)
        written.append((p, os.path.getsize(p)))
        if width == 1536:
            p = os.path.join(OUT_DIR, f'{stem}-1536.jpg')
            scaled.save(p, 'JPEG', quality=JPEG_QUALITY, optimize=True, progressive=True)
            written.append((p, os.path.getsize(p)))

    return written


CARD_SRC_DIR = os.path.expanduser('~/Desktop/Game images/Items/godforge_cards')
CARD_OUT_DIR = os.path.join(os.path.dirname(__file__), '..', 'src', 'assets', 'icons', 'runes')
CARD_QUALITY = 88


def build_cards() -> int:
    """Re-encode the card sheet crops as WebP. Returns bytes written."""
    os.makedirs(CARD_OUT_DIR, exist_ok=True)
    total = 0
    for name in sorted(os.listdir(CARD_SRC_DIR)):
        if not name.endswith('.png'):
            continue
        img = Image.open(os.path.join(CARD_SRC_DIR, name))
        if img.mode == 'RGBA' and img.getextrema()[3][0] < 255:
            # Not expected — see the note at the top. If a future card really
            # is cut out, say so rather than silently flattening it onto black.
            print(f'  warning: {name} has real transparency; kept as RGBA', file=sys.stderr)
        else:
            img = img.convert('RGB')
        out = os.path.join(CARD_OUT_DIR, name.replace('.png', '.webp'))
        img.save(out, 'WEBP', quality=CARD_QUALITY, method=6)
        total += os.path.getsize(out)
    return total


def main() -> int:
    if not os.path.isdir(SRC_DIR):
        print(f'error: source art not found at {SRC_DIR}', file=sys.stderr)
        return 1
    only = {a.split('=', 1)[1] for a in sys.argv if a.startswith('--only=')}
    check = '--check' in sys.argv

    jobs: list[tuple[str, str, bool]] = [(src, stem, True) for src, stem in SCENES.items()]
    jobs += [(src, stem, False) for src, stem in TOWNS.items()]
    if only:
        jobs = [j for j in jobs if j[1] in only]
        unknown = only - {j[1] for j in jobs}
        if unknown:
            print(f'error: unknown scene stem(s): {", ".join(sorted(unknown))}', file=sys.stderr)
            return 1

    total = 0
    built = 0
    for src_name, stem, required in sorted(jobs, key=lambda j: j[1]):
        src_path = os.path.join(SRC_DIR, f'{src_name}.png')
        if not os.path.isfile(src_path):
            if required:
                print(f'error: missing {src_path}', file=sys.stderr)
                return 1
            print(f'  {stem:28s} pending — no Locations/{src_name}.png yet')
            continue
        if check:
            print(f'  {stem:28s} ok')
            continue
        for path, size in build(src_path, stem):
            total += size
            print(f'  {os.path.basename(path):28s} {size // 1024:5d} KB')
        built += 1

    if check:
        return 0
    print(f'\n{built} scenes, {total // 1024} KB')

    if only or not os.path.isdir(CARD_SRC_DIR):
        if not only:
            print(f'cards skipped: {CARD_SRC_DIR} not found')
        return 0
    cards = build_cards()
    print(f'33 cards, {cards // 1024} KB')
    print(f'total {(total + cards) // 1024} KB')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
